function videoExists(url){
  return fetch(url, { method: "HEAD" }).then(r => r.ok).catch(() => false);
}
function videoBox(url, title){
  return videoExists(url).then(ok => {
    if(!ok) return "";
    return '<div class="video-box"><video controls playsinline preload="metadata" src="' + url + '"></video>' +
           '<p class="muted" style="margin-top:6px">' + title + '</p></div>';
  });
}

