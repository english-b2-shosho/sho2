const LS_KEY = "sho2-progress.v1";

function loadProgress(){
  try { return JSON.parse(localStorage.getItem(LS_KEY)) || { seen: {} }; }
  catch(e){ return { seen: {} }; }
}
function saveProgress(p){ localStorage.setItem(LS_KEY, JSON.stringify(p)); }
function markSeen(scId, idx){
  const p = loadProgress();
  if(!p.seen[scId]) p.seen[scId] = [];
  if(!p.seen[scId].includes(idx)) p.seen[scId].push(idx);
  saveProgress(p);
}
function seenCount(scId){ return (loadProgress().seen[scId] || []).length; }
function totalDone(){
  const p = loadProgress();
  return SCENARIOS.filter(s => (p.seen[s.id]||[]).length > 0).length;
}
function catDone(catId){
  const p = loadProgress();
  const list = SCENARIOS.filter(s => s.cat === catId);
  return list.filter(s => (p.seen[s.id]||[]).length > 0).length + "/" + list.length;
}
function catComplete(catId){
  const p = loadProgress();
  return SCENARIOS.filter(s => s.cat === catId).every(s => (p.seen[s.id]||[]).length > 0);
}

