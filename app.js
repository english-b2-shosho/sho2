function renderScenario(scId, choiceIdx){
  const s = SCENARIOS.find(x => x.id === scId);
  if(!s){ location.hash = "#/"; return; }
  const c = CATS.find(x => x.id === s.cat);
  const app = document.getElementById("app");
  const seen = loadProgress().seen[s.id] || [];
  let html =
    '<button class="back" onclick="location.hash=\'#/cat/' + c.id + '\'">› رجوع لـ' + c.name + '</button>' +
    '<div class="story"><div class="story-title">' + s.title + '</div><p>' + s.story + '</p></div>';

  if(choiceIdx === null || choiceIdx === undefined){
    html += '<h3 style="margin:10px 4px 2px">إنتي في الموقف ده... هتعملي إيه؟</h3>';
    s.choices.forEach((ch, i) => {
      html += '<button class="choice' + (seen.includes(i) ? ' seen' : '') + '" data-i="' + i + '">' + ch.t + '</button>';
    });
  } else {
    const ch = s.choices[choiceIdx];
    html +=
      '<div class="card"><p class="muted">اختيارك:</p><h3>' + ch.t + '</h3></div>' +
      '<div class="outcome"><h4>إيه اللي ممكن يحصل؟</h4><p>' + ch.o + '</p></div>' +
      '<div class="note"><strong>خدي بالك:</strong> ' + ch.n + '</div>' +
      '<button class="btn" id="try-other">جرّبي رد تاني 🔄</button>';
    const others = s.choices.map((_, i) => i).filter(i => i !== choiceIdx && !seen.includes(i));
    const next = SCENARIOS.filter(x => x.cat === s.cat).find(x => seenCount(x.id) === 0 && x.id !== s.id);
    if(next){
      html += '<a class="btn secondary" href="#/sc/' + next.id + '">الموقف اللي بعده: ' + next.title + '</a>';
    }
    html += '<a class="btn ghost" href="#/cat/' + c.id + '">رجوع لقائمة المواقف</a>';
  }
  app.innerHTML = html;

  app.querySelectorAll(".choice").forEach(btn => {
    btn.addEventListener("click", () => {
      const i = parseInt(btn.getAttribute("data-i"), 10);
      markSeen(s.id, i);
      location.hash = "#/sc/" + s.id + "/" + i;
    });
  });
  const tryOther = document.getElementById("try-other");
  if(tryOther) tryOther.addEventListener("click", () => { location.hash = "#/sc/" + s.id; });
}

function route(){
  const h = location.hash || "#/";
  const parts = h.replace(/^#\//, "").split("/");
  window.scrollTo(0, 0);
  if(parts[0] === "cat" && parts[1]) renderCat(parts[1]);
  else if(parts[0] === "sc" && parts[1]) renderScenario(parts[1], parts[2] !== undefined ? parseInt(parts[2], 10) : null);
  else renderHome();
}

window.addEventListener("hashchange", route);
route();

